#!/usr/bin/env python3
"""Generate SQL Server's regular-identifier character tables (#783).

SQL Server writes a name bare (as a *regular identifier*) only when its
characters are in the identifier classes of Unicode 3.2. Measured against the
server for every Basic Multilingual Plane character, the rule is:

- a first character is a Unicode 3.2 letter (`Lu`, `Ll`, `Lt`, `Lm`, `Lo`), a
  letter number (`Nl`), FULLWIDTH LOW LINE (U+FF3F), or ASCII `_ @ #`;
- a later character is any of those, or a Unicode 3.2 nonspacing or spacing
  mark (`Mn`, `Mc`), decimal digit (`Nd`), connector punctuation (`Pc`), format
  character (`Cf`), or ASCII `$`.

Supplementary characters are never part of a regular identifier. The ASCII
part of the rule lives in `dialect.rs`; this script writes the non-ASCII BMP
ranges from Python's bundled Unicode 3.2.0 database
(`unicodedata.ucd_3_2_0`). The
`sql_server_regular_identifier_tables_match_the_server` test in
`crates/graphql-orm/tests/identifier_quoting_properties.rs` checks every
non-ASCII BMP character against the owned SQL Server container.

Usage: python3 scripts/generate-mssql-identifier-tables.py [--check]
"""

import pathlib
import sys
import unicodedata

OUTPUT = (
    pathlib.Path(__file__).resolve().parent.parent
    / "crates/graphql-orm/src/graphql/orm/mssql_identifier_tables.rs"
)
START = {"Lu", "Ll", "Lt", "Lm", "Lo", "Nl"}
PART = {"Mn", "Mc", "Nd", "Pc", "Cf"}
FULLWIDTH_LOW_LINE = 0xFF3F


def ranges(predicate):
    found = []
    start = None
    for code_point in range(0x80, 0x10000):
        if 0xD800 <= code_point <= 0xDFFF:
            included = False
        else:
            included = predicate(code_point, unicodedata.ucd_3_2_0.category(chr(code_point)))
        if included and start is None:
            start = code_point
        elif not included and start is not None:
            found.append((start, code_point - 1))
            start = None
    if start is not None:
        found.append((start, 0xFFFF))
    return found


def table(name, doc, entries):
    lines = [f"/// {doc}", f"pub(super) const {name}: &[(u16, u16)] = &["]
    lines += [f"    (0x{low:04X}, 0x{high:04X})," for low, high in entries]
    lines.append("];")
    return "\n".join(lines)


def render():
    assert unicodedata.ucd_3_2_0.unidata_version == "3.2.0"
    header = (
        "// @generated by scripts/generate-mssql-identifier-tables.py from Unicode 3.2.0.\n"
        "// Do not edit by hand; rerun the script instead.\n"
        "//\n"
        "// Inclusive, sorted, non-overlapping ranges of non-ASCII Basic Multilingual\n"
        "// Plane characters that SQL Server reads as part of a regular identifier.\n"
    )
    start = table(
        "MSSQL_IDENTIFIER_START",
        "Characters that may start a regular identifier: Unicode 3.2 `L*` and `Nl`, and U+FF3F.",
        ranges(lambda code_point, category: category in START or code_point == FULLWIDTH_LOW_LINE),
    )
    part = table(
        "MSSQL_IDENTIFIER_PART",
        "Further characters allowed after the first: Unicode 3.2 `Mn`, `Mc`, `Nd`, `Pc` and `Cf`.",
        ranges(lambda code_point, category: category in PART and code_point != FULLWIDTH_LOW_LINE),
    )
    return f"{header}\n{start}\n\n{part}\n"


def main():
    rendered = render()
    if sys.argv[1:] == ["--check"]:
        if OUTPUT.read_text() != rendered:
            print(f"{OUTPUT} is stale; rerun {sys.argv[0]}", file=sys.stderr)
            return 1
        return 0
    if sys.argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    OUTPUT.write_text(rendered)
    return 0


if __name__ == "__main__":
    sys.exit(main())
